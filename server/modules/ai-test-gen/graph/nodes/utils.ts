const MAX_REACT_ROUNDS = 30;

// E3: Truncate large tool results to avoid context bloat
const MAX_TOOL_RESULT_CHARS = 6000;
function truncateToolResult(content: string): string {
  if (!content || typeof content !== 'string') return '';
  if (content.length <= MAX_TOOL_RESULT_CHARS) return content;
  return content.slice(0, MAX_TOOL_RESULT_CHARS) + `\n...(truncated, ${content.length} chars total)`;
}

function serializeToolArgs(args: unknown): string {
  if (args === undefined || args === null) return '';
  if (typeof args === 'string') return args;
  try {
    const s = JSON.stringify(args);
    return typeof s === 'string' ? s : '';
  } catch {
    return '';
  }
}

export class ToolStateProjectionError extends Error {
  constructor() {
    super('Tool state projection failed');
    this.name = 'ToolStateProjectionError';
  }
}

function serializeToolResult(result: unknown): { content: string; stateOutput: unknown } {
  if (typeof result === 'string') return { content: result, stateOutput: result };
  try {
    const content = JSON.stringify(result, null, 2);
    return typeof content === 'string'
      ? { content, stateOutput: JSON.parse(content) }
      : { content: 'null', stateOutput: null };
  } catch {
    return { content: 'null', stateOutput: null };
  }
}

function projectToolCallForState(
  skill: SkillDefinition,
  input: unknown,
  result: unknown,
  stateOutput: unknown,
  meta: { latencyMs: number; resultSize: number },
): { input: unknown; output: unknown } {
  if (!skill.summarizeForState) return { input, output: stateOutput };

  let projection: unknown;
  try {
    projection = skill.summarizeForState(input, result, meta);
  } catch {
    throw new ToolStateProjectionError();
  }
  let normalizedProjection: unknown;
  try {
    const serialized = JSON.stringify(projection);
    if (serialized === undefined) throw new ToolStateProjectionError();
    normalizedProjection = JSON.parse(serialized);
  } catch {
    throw new ToolStateProjectionError();
  }
  if (!normalizedProjection
    || typeof normalizedProjection !== 'object'
    || Array.isArray(normalizedProjection)
    || !Object.hasOwn(normalizedProjection, 'input')
    || !Object.hasOwn(normalizedProjection, 'output')) {
    throw new ToolStateProjectionError();
  }
  return normalizedProjection as { input: unknown; output: unknown };
}

function extractedValueSummary(value: unknown): { type: string; keys: string[]; draftTestCases: string } {
  const keys = value && typeof value === 'object' ? Object.keys(value as Record<string, unknown>) : [];
  const draftTestCases = (value as any)?.draftTestCases ? typeof (value as any).draftTestCases : 'missing';
  return { type: typeof value, keys, draftTestCases };
}

/**
 * Consume an extraction-stage stream (Phase 1.5 nudge / Phase 2 retry loop),
 * accumulating content, token usage and the provider finishReason.
 * finishReason === 'length' means the output was truncated by max_tokens —
 * surfaced so callers can distinguish truncation from schema failures
 * (retrying a truncated prompt only truncates again).
 */
interface ExtractStreamResult {
  content: string;
  finishReason?: string;
}

async function consumeExtractionStream(
  provider: AIProvider,
  messages: ChatMessage[],
  options: ChatOptions,
  observer: { onThinking?: (name: string, text: string, type: 'reasoning' | 'content', phase: 'react' | 'extraction') => void },
  name: string,
  usage: { input: number; output: number; reasoning: number; cached: number },
): Promise<ExtractStreamResult> {
  let content = '';
  let finishReason: string | undefined;
  for await (const chunk of provider.streamChat(messages, options)) {
    if (chunk.type === 'content' && chunk.content) {
      content += chunk.content;
      observer?.onThinking?.(name, chunk.content, 'content', 'extraction');
    }
    if (chunk.type === 'done') {
      if (chunk.usage) {
        usage.input += (chunk.usage.promptTokens || 0);
        usage.output += (chunk.usage.completionTokens || 0);
        usage.reasoning += (chunk.usage.reasoningTokens || 0);
        usage.cached += (chunk.usage.cachedPromptTokens || 0);
      }
      finishReason = chunk.finishReason;
    }
  }
  return { content, finishReason };
}

interface ReActResult {
  contentText: string;
  thinkingText: string;
  toolCallRecords: ToolCallRecord[];
  usage: { input: number; output: number; reasoning: number; cached: number };
  conversationMessages: ChatMessage[];
}

/**
 * Execute the ReAct loop: LLM thinks → call tool → observe result → continue thinking
 * At most MAX_REACT_ROUNDS rounds; exit when there are no tool_calls
 */
async function runAgentReActLoop(
  provider: AIProvider,
  messages: ChatMessage[],
  skills: SkillDefinition[],
  outputProfile: StructuredOutputProfile<unknown>,
  observer: {
    onStep?: (name: string, idx: number, step: string) => void;
    onThinking?: (name: string, text: string, type: 'reasoning' | 'content', phase: 'react' | 'extraction') => void;
    onToolCall?: (name: string, toolCall: ToolCallRecord) => void;
  },
  agentName: string,
  extra: Partial<ChatOptions> | undefined,
): Promise<ReActResult> {
  const skillMap = new Map(skills.map((s) => [s.name, s]));
  const log = Log.for(`react:${agentName}`);
  log.info(`ReAct loop start ── ${skills.length} skills: ${skills.map(s => s.name).join(', ')}`);
  const allMessages: ChatMessage[] = [...messages];
  let contentText = '';
  let thinkingText = '';
  const toolCallRecords: ReActResult['toolCallRecords'] = [];
  let capturedUsage = {
    input: 0,
    output: 0,
    reasoning: 0,
    cached: 0,
  };
  let totalRounds = 0;

  observer?.onStep?.(agentName, 0, 'Phase 1: Analysis started');

  for (let round = 0; round < MAX_REACT_ROUNDS; round++) {
    totalRounds = round + 1;
    // Stream call to LLM (with tools)
    let roundContent = '';
    let roundThinking = '';
    const pendingToolCalls: ToolCall[] = [];

    // 上下文窗口压缩：只发送 base + 最近几轮完整消息，更早轮次的工具结果摘要化，
    // 防止每轮重发全部历史导致 O(n²) token 膨胀（实测 Designer 单 run input 260k tokens）。
    const sendMessages = compactReActConversation(allMessages, messages.length);

    for await (const chunk of provider.streamChat(sendMessages, buildThinkingChatOptions(skills, extra))) {
      if (chunk.type === 'reasoning' && chunk.content) {
        roundThinking += chunk.content;
        observer?.onThinking?.(agentName, chunk.content, 'reasoning', 'react');
      }
      if (chunk.type === 'content' && chunk.content) {
        roundContent += chunk.content;
        observer?.onThinking?.(agentName, chunk.content, 'content', 'react');
      }
      if (chunk.type === 'tool_call_start' && chunk.toolCall) {
        pendingToolCalls.push(chunk.toolCall);
      }
      if (chunk.type === 'tool_call_delta' && chunk.toolCall) {
        const existing = pendingToolCalls.find((tc) => tc.id === chunk.toolCall!.id);
        if (existing) {
          existing.args = chunk.toolCall.args; // The last delta contains the complete args
        } else {
          pendingToolCalls.push(chunk.toolCall);
        }
      }
      if (chunk.type === 'tool_call_end' && chunk.toolCall) {
        const existing = pendingToolCalls.find((tc) => tc.id === chunk.toolCall!.id);
        if (existing) {
          existing.args = chunk.toolCall.args;
          existing.malformed = chunk.toolCall.malformed;
        }
      }
      if (chunk.type === 'done' && chunk.usage) {
        capturedUsage = {
          input: capturedUsage.input + (chunk.usage.promptTokens || 0),
          output: capturedUsage.output + (chunk.usage.completionTokens || 0),
          reasoning: capturedUsage.reasoning + (chunk.usage.reasoningTokens || 0),
          cached: capturedUsage.cached + (chunk.usage.cachedPromptTokens || 0),
        };
      }
    }

    contentText += roundContent;
    thinkingText += roundThinking;

    // E1: Early termination check — if the same skill is called for 3 consecutive rounds, force terminate
    // emit_* are BATCH-DECLARATION tools: the LLM is SUPPOSED to call them
    // repeatedly (once per case/condition). Exclude them from the stuck-detection so the
    // loop isn't aborted mid-way through a tool-based declaration (a real failure that forced
    // the LLM to abandon Mode A and fall back to JSON).
    const nonDeclarationRecords = toolCallRecords.filter(
      (r) => !r.name.startsWith('emit_'),
    );
    if (nonDeclarationRecords.length >= 3) {
      const recentCalls = nonDeclarationRecords.slice(-3);
      const uniqueRecent = new Set(recentCalls.map(r => r.name));
      // Only treat as "stuck" if the SAME skill is called 3 times with IDENTICAL args.
      // E.g. istqb_guide loaded for 3 different techniques (3 different technique sets)
      // is legitimate exploration, not a stuck loop — killing it here caused analyst to
      // abandon emit_condition (zero conditions were ever emitted in the failing run).
      const allSameArgs = recentCalls.every((r) =>
        JSON.stringify(r.input) === JSON.stringify(recentCalls[0].input),
      );
      if (uniqueRecent.size === 1 && allSameArgs) {
        log.info(`Early termination: stuck repeating skill "${recentCalls[0].name}"`);
        break;
      }
    }

    if (pendingToolCalls.length === 0) {
      log.info(`Round ${round + 1}: no tool calls, exiting loop`);
      break;
    }

    log.info(`Round ${round + 1}: ${pendingToolCalls.length} tool calls: ${summarizeToolNames(pendingToolCalls.map(tc => tc.name))}`);

    // Filter out empty-named tool calls (hallucinated by some providers)
    const namedToolCalls = pendingToolCalls.filter(tc => tc.name);
    const skippedCount = pendingToolCalls.length - namedToolCalls.length;
    if (skippedCount > 0) log.warn(`Skipped ${skippedCount} tool call(s) with empty name`);

    if (namedToolCalls.length === 0) {
      log.info(`No named tool calls, exiting loop`);
      break;
    }

    // Execute tool calls
    const toolResults: ChatMessage[] = [];
    const criticalTools = new Set(['requirement_detail_query', 'istqb_guide', 'requirement_graph_query', 'flow_detail_query', 'html_knowledge_query']);
    // emit_* 调用按批合并日志（LLM 常在一轮内连发 10+ 次，逐条打印会刷屏）
    const emitIdsByTool = new Map<string, string[]>();

    for (const tc of namedToolCalls) {
      const skill = skillMap.get(tc.name);
      if (!skill) {
        log.warn(`Unknown tool call: ${tc.name}`);
        toolResults.push({ role: 'tool', content: JSON.stringify({ error: `Unknown tool: "${tc.name}". You can only call the tools explicitly provided to you. Do NOT invent or call any tool that is not in the available tool list. Continue your analysis in plain text and let the automatic extraction step produce the final structured output.` }, null, 2), toolCallId: tc.id });
        continue;
      }

      const skillStart = Date.now();
      try {
        let args = tc.args;
        if (typeof tc.args === 'string') {
          try {
            args = JSON.parse(tc.args);
          } catch (error) {
            // The HTML skill validates its own untrusted model input and returns
            // a bounded correction instead of turning malformed arguments into
            // a critical retrieval failure.
            if (tc.name !== 'html_knowledge_query') throw error;
          }
        }

        // Tool-schema validation at call time — only for emit_case.
        // Its enum/refine (verb whitelist, data-required, expectation coupling) MUST be
        // enforced HERE — otherwise invalid args reach emit-extract and only get
        // rejected later by validateStepContract, wasting the whole draft + a Phase 2
        // retry (real logs: "refresh browser page" non-vocab verb, fill-without-data,
        // element-state value "visible" all acked). Reject immediately with a clear
        // message so the LLM self-corrects in the next round.
        // Other skills (data queries, html_knowledge_query) intentionally handle their
        // own untrusted/malformed input leniently — do not gate them on schema here.
        const isEmitTool = tc.name.startsWith('emit_');
        const schemaCheck = isEmitTool ? skill.schema?.safeParse(args) : undefined;
        if (schemaCheck && !schemaCheck.success) {
          const reasons = schemaCheck.error.issues
            .map((i) => `${i.path.join('.') || '(root)'}: ${i.message}`)
            .join('; ');
          const message = `${tc.name} arguments rejected by schema: ${reasons}. Fix the arguments and call the tool again.`;
          log.warn(message);
          const toolCallRecord: ToolCallRecord = {
            name: tc.name,
            input: tc.args,
            output: { error: message },
            latencyMs: Date.now() - skillStart,
          };
          toolCallRecords.push(toolCallRecord);
          observer?.onToolCall?.(agentName, toolCallRecord);
          toolResults.push({ role: 'tool', content: JSON.stringify({ error: message }, null, 2), toolCallId: tc.id });
          observer?.onStep?.(agentName, round + 1, `${tc.name} args rejected`);
          continue;
        }

        const result = await skill.func(args as Record<string, unknown>);
        const latencyMs = Date.now() - skillStart;
        const serializedResult = serializeToolResult(result);
        const persisted = projectToolCallForState(skill, args, result, serializedResult.stateOutput, {
          latencyMs,
          resultSize: serializedResult.content.length,
        });
        if (isEmitTool) {
          const id = String((args as any)?.id ?? (args as any)?.caseId ?? (args as any)?.conditionId ?? '');
          if (id) {
            const list = emitIdsByTool.get(tc.name) ?? [];
            if (!list.includes(id)) list.push(id);
            emitIdsByTool.set(tc.name, list);
          }
        } else {
          log.kv(`${tc.name}`, `completed (${latencyMs}ms)`);
        }
        const toolCallRecord: ToolCallRecord = {
          name: tc.name,
          input: persisted.input,
          output: persisted.output,
          latencyMs,
        };
        toolCallRecords.push(toolCallRecord);
        observer?.onToolCall?.(agentName, toolCallRecord);
        toolResults.push({ role: 'tool', content: truncateToolResult(serializedResult.content), toolCallId: tc.id });
        observer?.onStep?.(agentName, round + 1, `Called ${tc.name} (${latencyMs}ms)`);
      } catch (err: any) {
        const latencyMs = Date.now() - skillStart;
        log.error(`Skill ${tc.name} FAILED (${latencyMs}ms): ${err.message}`);

        if (err instanceof ToolStateProjectionError) throw err;
        
        // Critical Tool Failure - Abort immediately instead of letting the LLM hallucinate
        if (criticalTools.has(tc.name)) {
          log.error(`CRITICAL TOOL FAILURE: ${tc.name} failed. Aborting ReAct loop to prevent hallucination.`);
          throw new Error(`Critical tool execution failed: [${tc.name}] ${err.message}. Aborting to prevent context hallucination.`);
        }

        const toolCallRecord: ToolCallRecord = {
          name: tc.name,
          input: tc.args,
          output: { error: err.message },
          latencyMs,
        };
        toolCallRecords.push(toolCallRecord);
        observer?.onToolCall?.(agentName, toolCallRecord);
        toolResults.push({ role: 'tool', content: JSON.stringify({ error: err.message }, null, 2), toolCallId: tc.id });
      }
    }

    for (const [toolName, ids] of emitIdsByTool) {
      const range = ids.length > 1 ? ` (${ids[0]}..${ids[ids.length - 1]})` : '';
      log.kv('emit', `${toolName} ×${ids.length} acked${range}`);
    }

    // Append assistant message (with tool_calls) + tool results
    allMessages.push({
      role: 'assistant',
      content: roundContent || null as any,
      toolCalls: namedToolCalls.map((tc) => ({
        type: 'function' as const,
        function: { name: tc.name, arguments: serializeToolArgs(tc.args) },
        id: tc.id,
      })),
    });

    allMessages.push(...toolResults);
  }

  const toolCallCount = toolCallRecords.length;
  observer?.onStep?.(agentName, 1, toolCallCount > 0
    ? `Phase 1: Analysis completed (${totalRounds} rounds, ${toolCallCount} tools)`
    : `Phase 1: Analysis completed (${totalRounds} rounds)`);

  return { contentText, thinkingText, toolCallRecords, usage: capturedUsage, conversationMessages: allMessages };
}

// ============================================================
// Targeted schema repair — 定点修复，替代"整体重新生成"
//
// 业界（Anthropic/OpenAI structured outputs）靠 API 层 constrained decoding 从根上
// 消灭 schema 违规。本项目 openai-compatible provider 因兼容性故意降级到 json_object
//（无 schema 约束），所以 zod 后校验仍会失败。此时不要"贴完整 schema/错误列表 + 让
// 模型从头重生成整个对象"，而是只把**出错字段的 path + 原因**反馈回去，让模型在
// 上一份 JSON 上做最小改动——同时省 input token（精简反馈）与 output token（最小改动）。
// ============================================================

interface ZodIssueLike {
  path?: Array<string | number>;
  message?: string;
}

function extractRepairIssues(error: unknown, maxIssues = 8): string[] {
  const issues = (error as { issues?: ZodIssueLike[] } | null | undefined)?.issues ?? [];
  const lines: string[] = [];
  const seen = new Set<string>();
  for (const issue of issues) {
    const path = (issue.path ?? []).join('.') || '(root)';
    const message = issue.message ?? 'invalid value';
    const key = `${path}:${message}`;
    if (seen.has(key)) continue;
    seen.add(key);
    lines.push(`- ${path}: ${message}`);
    if (lines.length >= maxIssues) break;
  }
  return lines;
}

function buildSchemaRepairFeedback(extractContent: string, schemaErr: unknown): ChatMessage[] {
  const lines = extractRepairIssues(schemaErr);
  const repairPrompt = [
    'The JSON you produced is valid JSON, but it failed schema validation on these fields:',
    ...lines,
    '',
    'Fix ONLY the fields listed above. Keep every other field and value exactly as you wrote them. Output the complete corrected JSON object with no text before or after it.',
  ].join('\n');
  return [
    { role: 'assistant' as const, content: extractContent },
    { role: 'user' as const, content: repairPrompt },
  ];
}

// ============================================================
// Phase 1.25 emit-repair — 复用已声明的 emit_* 实体，定点修补
//
// emit 模式的核心优势：实体已通过 toolCallRecords 落盘。跨字段校验失败时，
// 不再落整批 Phase 2 全量 JSON 重发（烧全量 output token），而是把错误回投进
// 同一会话、只开放 emit_* 工具，让 LLM 重发坏掉的实体（last-write-wins 覆盖），
// 再 merge 重提取。修复成本 ≈ 坏实体数 × 单条调用，远小于整批重生成。
// ============================================================

/** 用结构化缺口清单替代报错原文：已声明 id + 每条缺口的可执行修复指令。 */
function buildRepairPrompt(existingRecords: ToolCallRecord[], gaps: RepairGap[], fallbackErrorText: string): string {
  const declaredIds = [...new Set(
    existingRecords
      .filter((r) => r.name.startsWith('emit_'))
      .map((r) => String((r.input as any)?.id ?? (r.input as any)?.caseId ?? (r.input as any)?.conditionId ?? '').trim())
      .filter(Boolean),
  )];

  const gapLines = gaps.slice(0, 12).map((g) =>
    `- [${g.type}] ${g.entityId}${g.field ? ` (${g.field})` : ''}${g.badValue ? ` — bad value "${g.badValue}"` : ''} → ${g.fix}`,
  );

  const lines = [
    'Your emitted entities failed validation. Re-emit ONLY the entities with gaps below via the matching `emit_*` tool (same id overwrites the previous declaration).',
    '',
    `Already declared entities: ${declaredIds.length > 0 ? declaredIds.join(', ') : '(none)'}`,
    '',
    `Gaps to fix (${gaps.length}):`,
  ];
  if (gapLines.length > 0) {
    lines.push(...gapLines);
  } else {
    lines.push(...fallbackErrorText.split('\n').slice(0, 14).map((l) => `  ${l}`));
  }
  lines.push('', 'Leave every passing entity untouched. Do NOT emit a JSON block. Stop after re-emitting the fixes.');
  return lines.join('\n');
}

/** 定向补缺：只列缺失实体（纯增量，最便宜），不发整批 schema、不重发已有实体。 */
function buildCompletionPrompt(missingGaps: RepairGap[]): string {
  return [
    'You are still MISSING some entities. Emit ONLY the missing entities below via the matching `emit_*` tool — do NOT re-emit anything you already emitted.',
    '',
    'Missing entities to add:',
    ...missingGaps.slice(0, 12).map((g) => `- ${g.fix}`),
    '',
    'Do NOT emit a JSON block. Stop after emitting the missing entities.',
  ].join('\n');
}

interface EmitRepairDeps<T> {
  provider: AIProvider;
  llmLog: ReturnType<typeof Log.for>;
  observer?: {
    onStep?: (name: string, idx: number, step: string) => void;
    onThinking?: (name: string, text: string, type: 'reasoning' | 'content', phase: 'react' | 'extraction') => void;
    onToolCall?: (name: string, toolCall: ToolCallRecord) => void;
  };
  name: string;
  agentName: string;
  extra?: Partial<ChatOptions>;
  skills: SkillDefinition[];
  outputProfile: StructuredOutputProfile<T>;
  parseErr: unknown;
  conversationMessages: ChatMessage[];
  existingRecords: ToolCallRecord[];
}

const MAX_EMIT_REPAIR_ROUNDS = 3;

async function runEmitRepair<T>(deps: EmitRepairDeps<T>): Promise<{ output: T; usage: { input: number; output: number; reasoning: number; cached: number }; toolCallRecords: ToolCallRecord[] } | null> {
  const { provider, llmLog, observer, name, agentName, extra, skills, outputProfile, parseErr, conversationMessages, existingRecords } = deps;
  // 只开放 emit_* 工具：修复轮不应再触发数据查询等重活。
  const emitSkills = skills.filter((s) => s.name.startsWith('emit_'));
  if (emitSkills.length === 0) return null;

  let records = [...existingRecords];
  let curConversation = [...conversationMessages];
  let curGaps = extractRepairGaps(parseErr);
  let curErrorText = outputProfile.formatValidationError(parseErr);

  const emitCount = existingRecords.filter((r) => r.name.startsWith('emit_')).length;
  llmLog.warn(`emit-repair attribution: ${formatRepairPlan({ mode: 'emit', emitCount, layer: 'global', gaps: curGaps })}`);

  for (let attempt = 1; attempt <= MAX_EMIT_REPAIR_ROUNDS; attempt++) {
    llmLog.info(`emit-repair attempt ${attempt}/${MAX_EMIT_REPAIR_ROUNDS} (skills: ${emitSkills.map((s) => s.name).join(', ')})`);
    observer?.onStep?.(name, 2, `Phase 1.25: Emit-repair attempt ${attempt}/${MAX_EMIT_REPAIR_ROUNDS}`);

    const repairPrompt = buildRepairPrompt(records, curGaps, curErrorText);

    const repairMessages: ChatMessage[] = [
      ...curConversation,
      { role: 'user' as const, content: repairPrompt },
    ];

    const repair = await runAgentReActLoop(
      provider,
      repairMessages,
      emitSkills,
      outputProfile,
      {
        onStep: observer?.onStep,
        onThinking: observer?.onThinking,
        onToolCall: observer?.onToolCall,
      },
      name,
      extra,
    );

    // 追加本轮新增的会话消息（供下一轮上下文）。
    curConversation = [...curConversation, ...repair.conversationMessages.slice(curConversation.length)];

    records = [...records, ...repair.toolCallRecords];
    const merged = outputProfile.emitExtract?.(records, repair.contentText, name) ?? null;
    if (!merged) {
      llmLog.warn(`emit-repair attempt ${attempt}: no valid entities assembled from repaired records`);
      continue;
    }
    try {
      const normalized = outputProfile.normalize(merged);
      const result = outputProfile.parse(normalized);
      llmLog.success(`emit-repair converged on attempt ${attempt}`);
      observer?.onStep?.(name, 2, 'Phase 1.25: Emit-repair success');
      return { output: result, usage: repair.usage, toolCallRecords: records };
    } catch (repairErr: any) {
      curErrorText = outputProfile.formatValidationError(repairErr);
      curGaps = extractRepairGaps(repairErr);
      llmLog.warn(`emit-repair attempt ${attempt} still invalid: ${curGaps.length} gap(s)\n${curErrorText.split('\n').slice(0, 6).join('\n')}`);
    }
  }

  // ── Phase 1.26 定向补缺 ──
  // 主循环收敛失败时，若缺口以"漏实体"为主（missing-entity），做一轮纯补缺而非
  // 直接落整批 Phase 2：只发"补这些缺失实体"的窄指令（纯增量、最便宜、最不易截断）。
  const missingGaps = curGaps.filter((g) => g.type === 'missing-entity');
  if (missingGaps.length > 0) {
    observer?.onStep?.(name, 2, 'Phase 1.26: Targeted completion');
    llmLog.info(`targeted completion: ${missingGaps.length} missing entity/entities`);

    const completionPrompt = buildCompletionPrompt(missingGaps);
    const completion = await runAgentReActLoop(
      provider,
      [...curConversation, { role: 'user' as const, content: completionPrompt }],
      emitSkills,
      outputProfile,
      {
        onStep: observer?.onStep,
        onThinking: observer?.onThinking,
        onToolCall: observer?.onToolCall,
      },
      name,
      extra,
    );

    const completedRecords = [...records, ...completion.toolCallRecords];
    const completedMerged = outputProfile.emitExtract?.(completedRecords, completion.contentText, name) ?? null;
    if (completedMerged) {
      try {
        const result = outputProfile.parse(outputProfile.normalize(completedMerged));
        llmLog.success('Phase 1.26 targeted completion converged');
        observer?.onStep?.(name, 2, 'Phase 1.26: Targeted completion success');
        return { output: result, usage: completion.usage, toolCallRecords: completedRecords };
      } catch (err: any) {
        llmLog.warn(`Phase 1.26 completion still invalid: ${outputProfile.formatValidationError(err).split('\n')[0]}`);
      }
    }
  }

  return null;
}

