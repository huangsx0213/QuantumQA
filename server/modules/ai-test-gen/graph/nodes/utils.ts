/**
 * Provider reported finishReason === 'length': the output was cut off by
 * max_tokens. Retrying the same prompt only truncates again — the caller
 * (orchestrator) must shrink the batch instead of re-entering the retry loop.
 */
export class TruncatedOutputError extends Error {
  constructor(readonly agent: string, readonly phase: string, readonly partialLength: number) {
    super(`[${agent}] ${phase} output truncated by max_tokens (${partialLength} chars). Retry with a smaller batch — re-sending the same prompt will truncate again.`);
    this.name = 'TruncatedOutputError';
  }
}

/**
 * Compress repeated tool names into "name ×N" (order of first appearance).
 * ReAct rounds with batched emit_case would otherwise print
 * the same name 10+ times per line.
 */
export function summarizeToolNames(names: string[]): string {
  const counts = new Map<string, number>();
  for (const n of names) counts.set(n, (counts.get(n) ?? 0) + 1);
  return [...counts].map(([n, c]) => (c > 1 ? `${n} ×${c}` : n)).join(', ');
}

/**
 * Project raw ReAct tool-call records into the state's `skillCalls` channel.
 * Every agent node persists the same shape, so this lives in one place.
 */
export function toSkillCallRecords(
  agentName: string,
  toolCallRecords: ToolCallRecord[] | undefined,
): SkillCallRecord[] {
  return (toolCallRecords ?? []).map((tc) => ({
    agent: agentName,
    skillName: tc.name,
    input: tc.input,
    output: tc.output,
    latencyMs: tc.latencyMs,
    timestamp: Date.now(),
  }));
}

/**
 * Convert SkillDefinition[] to ChatOptions.tools format
 */
export function skillsToChatTools(skills: SkillDefinition[]): ChatOptions['tools'] {
  if (!skills || skills.length === 0) return undefined;
  return skills.map((s) => ({
    name: s.name,
    description: s.description,
    parameters: zodToJsonSchema(s.schema) as any,
  }));
}

/**
 * Strip fields the builder always overrides (temperature/responseFormat/tools/
 * toolChoice) from `extra`, so per-call overrides never resurrect a value the
 * Phase 1 / Phase 2 options explicitly control.
 */
function stripOptionOverrides(extra?: Partial<ChatOptions>): Partial<ChatOptions> {
  const { temperature: _temperature, responseFormat: _responseFormat, tools: _tools, toolChoice: _toolChoice, ...rest } = extra ?? {};
  return rest;
}

/** Phase 1 (ReAct) temperature — exported so ARCHITECTURE.md can bind to it. */
export const PHASE1_TEMPERATURE = 0.5;
/** Phase 2 (extraction) temperature — exported so ARCHITECTURE.md can bind to it. */
export const PHASE2_TEMPERATURE = 0;

/**
 * Build ChatOptions: Phase 1 thinking + ReAct stage
 * Only expose business tools; final structured output is generated by the subsequent extraction stage.
 */
export function buildThinkingChatOptions(
  skills: SkillDefinition[],
  extra?: Partial<ChatOptions>,
): ChatOptions {
  const allowedExtra = stripOptionOverrides(extra);
  
  // Build tool list: only business skills. Final JSON is generated by the subsequent extraction stage to avoid the thinking stage depending on the model proactively submitting a structured payload.
  const businessTools = skillsToChatTools(skills);
  
  return {
    temperature: PHASE1_TEMPERATURE,
    tools: businessTools,
    toolChoice: businessTools && businessTools.length > 0 ? 'auto' : undefined,
    ...allowedExtra,
  };
}

/**
 * Build ChatOptions: Phase 2 extraction stage, using json_schema response_format
 */
export function buildExtractionChatOptions(
  outputProfile: StructuredOutputProfile<unknown>,
  extra?: Partial<ChatOptions>,
): ChatOptions {
  const allowedExtra = stripOptionOverrides(extra);
  return {
    jsonSchema: outputProfile.toolSchema,
    temperature: PHASE2_TEMPERATURE,
    ...allowedExtra,
  };
}

/**
 * Build the Phase 2 extraction prompt, including schema constraints and the
 * compact ground-truth fact block (F5) the runtime cross-field validation
 * checks against.
 */
export function buildExtractionPrompt(outputProfile: StructuredOutputProfile<unknown>): string {
  const schema = outputProfile.toolSchema;
  const hints = outputProfile.extractionHints;
  const hintsSection = hints ? `\n\nAdditional constraints (JSON Schema cannot express these — follow strictly):\n${hints}` : '';
  const contextSection = outputProfile.extractionContext
    ? `\n\nGround-truth facts (validate against these — do NOT invent ids):\n${outputProfile.extractionContext}`
    : '';
  return `Based on the analysis above, output a single JSON object matching this schema. Do NOT include any text before or after the JSON.

Schema:
${JSON.stringify(schema, null, 2)}${hintsSection}${contextSection}`;
}

